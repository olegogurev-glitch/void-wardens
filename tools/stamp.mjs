// Cache-busting for deploys (no build step, no dependencies).
//   node tools/stamp.mjs
//
// Adds a content fingerprint to every file the page loads, so after an update browsers
// fetch exactly the files that changed and never mix old and new modules:
//   • css/style.css   →  css/style.css?v=<hash>
//   • src/main.js     →  src/main.js?v=<hash>
//   • every other src/*.js module is remapped through an <script type="importmap">,
//     so relative imports like './config.js' resolve to './src/config.js?v=<hash>'.
// Safe to run repeatedly; it only rewrites index.html when something changed.
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const hash = (file) => crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT, file))).digest('hex').slice(0, 10);

const modules = fs.readdirSync(path.join(ROOT, 'src')).filter((f) => f.endsWith('.js')).sort();
const imports = {};
for (const f of modules) imports[`./src/${f}`] = `./src/${f}?v=${hash('src/' + f)}`;
const importMap = `<script type="importmap">\n${JSON.stringify({ imports }, null, 2).replace(/^/gm, '  ')}\n  </script>`;

const htmlPath = path.join(ROOT, 'index.html');
const before = fs.readFileSync(htmlPath, 'utf8');
let html = before;

const START = '<!-- importmap:start (generated by tools/stamp.mjs) -->', END = '<!-- importmap:end -->';
const block = `${START}\n  ${importMap}\n  ${END}`;
if (html.includes(START)) html = html.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`), block);
else html = html.replace('</head>', `  ${block}\n</head>`);

html = html.replace(/href="css\/style\.css(\?v=[^"]*)?"/, `href="css/style.css?v=${hash('css/style.css')}"`);
html = html.replace(/src="src\/main\.js(\?v=[^"]*)?"/, `src="src/main.js?v=${hash('src/main.js')}"`);

if (html !== before) { fs.writeFileSync(htmlPath, html); console.log(`stamped index.html: ${modules.length} modules + stylesheet`); }
else console.log('index.html already up to date');
